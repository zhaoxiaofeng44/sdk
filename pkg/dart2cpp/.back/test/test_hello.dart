void main() {
  print('Hello, World!');
  var x = 42;
  var y = x + 1;
  print('x = $x, y = $y');

  // 测试基础类型
  int age = 25;
  double height = 1.75;
  bool isStudent = true;
  String name = 'Alice';

  print('Name: $name, Age: $age, Height: $height, Is Student: $isStudent');

  // 测试集合
  var numbers = [1, 2, 3, 4, 5];
  var fruits = {'apple', 'banana', 'orange'};
  var scores = {'math': 95, 'english': 88, 'science': 92};

  print('Numbers: $numbers');
  print('Fruits: $fruits');
  print('Scores: $scores');
}
