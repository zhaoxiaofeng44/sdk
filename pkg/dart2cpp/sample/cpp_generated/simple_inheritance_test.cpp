#include "dart2cpp.h"

// ============================================================================
// 类: Animal
// ============================================================================

class Animal {
public:
  String name;
  Animal(String name) : name(name) {
  }
  
};

// ============================================================================
// 类: Dog
// ============================================================================

class Dog : public Animal {
public:
  Dog(String name) : Animal(name) {
  }
  
};

// ============================================================================
// 类: Cat
// ============================================================================

class Cat : public Animal {
public:
  Cat(String name) : Animal(name) {
  }
  
};

// ============================================================================
// 类: Address
// ============================================================================

class Address {
public:
  String street;
  Address(String street) : street(street) {
  }
  
};

// ============================================================================
// 主函数
// ============================================================================

int main() {
  try {
    dart_print(dart_string("✅ 继承测试成功"));
    return 0;
  } catch (const std::exception& e) {
    std::cerr << "Error: " << e.what() << std::endl;
    return 1;
  }
}